// Regenerates packages/app-core/src/metadata/bangumi-openapi.ts from the pinned Bangumi OpenAPI spec.
// openapi-typescript 7 drives the TypeScript compiler API, which TypeScript 7 does not ship, so the generator runs in an
// isolated folder under dist/ with TypeScript 5.9. Nothing from that folder enters the repository or the app.
//   node scripts/generate-bangumi-types.mjs [--spec path/to/v0.yaml]
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPEC_COMMIT = "a7055f2dca7286d6963aaa7928345eeca6293e2b";
const SPEC_SHA256 = "5a7ddb7ddec132293b1aa08102e6ac63e31b2925574658e927d6f931df2519da";
const SPEC_URL = `https://raw.githubusercontent.com/bangumi/api/${SPEC_COMMIT}/open-api/v0.yaml`;
const target = path.join(root, "packages/app-core/src/metadata/bangumi-openapi.ts");
const work = path.join(root, "dist/tools/openapi-gen");
fs.mkdirSync(work, { recursive: true });

const flag = process.argv.indexOf("--spec");
const specFile = path.join(work, "v0.yaml");
if (flag >= 0) fs.copyFileSync(process.argv[flag + 1], specFile);
else fs.writeFileSync(specFile, Buffer.from(await (await fetch(SPEC_URL)).arrayBuffer()));
const sha = createHash("sha256").update(fs.readFileSync(specFile)).digest("hex");
if (sha !== SPEC_SHA256) throw new Error(`the spec does not match the pinned commit (sha256 ${sha})`);

fs.writeFileSync(path.join(work, "package.json"), JSON.stringify({ name: "openapi-gen", private: true, version: "0.0.0" }));
const npm = process.platform === "win32" ? "npm.cmd" : "npm";
if (!fs.existsSync(path.join(work, "node_modules/openapi-typescript"))) {
  execFileSync(npm, ["install", "--no-audit", "--no-fund", "openapi-typescript@7.13.0", "typescript@5.9.2"], { cwd: work, stdio: "inherit", shell: process.platform === "win32" });
}
const out = path.join(work, "out.d.ts");
execFileSync(process.execPath, [path.join(work, "node_modules/openapi-typescript/bin/cli.js"), specFile, "-o", out], { cwd: work, stdio: "inherit" });
const header = `/**\n * Bangumi API v0 types, generated by openapi-typescript 7.13.0 (run under TypeScript 5.9).\n * Spec: ${SPEC_URL}\n * Spec commit ${SPEC_COMMIT}, sha256 ${SPEC_SHA256}.\n * Regenerate with: node scripts/generate-bangumi-types.mjs\n */\n`;
fs.writeFileSync(target, header + fs.readFileSync(out, "utf8"));
console.log(`wrote ${path.relative(root, target)}`);
